const supportedLanguages = ["en", "bn"];

const normalizeLanguage = (value) => {
  const language = String(value || "en").toLowerCase().split(/[,-]/)[0].trim();
  return supportedLanguages.includes(language) ? language : "en";
};

const t = (code, language = "en") => translations[normalizeLanguage(language)][code] || translations.en[code] || code;

module.exports = { normalizeLanguage, supportedLanguages, t };
